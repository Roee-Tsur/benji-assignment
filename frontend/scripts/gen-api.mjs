// Generates app/api/schema.d.ts from the backend's OpenAPI schema.
// The schema is read from the FastAPI app itself, so no server needs to be running.
// `--check` fails instead of writing when the committed file is stale (CI runs it).
import { execFileSync } from 'node:child_process'
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'

const backendDir = fileURLToPath(new URL('../../backend', import.meta.url))
const outFile = fileURLToPath(new URL('../app/api/schema.d.ts', import.meta.url))
const check = process.argv.includes('--check')

const schema = execFileSync(
  'uv',
  ['run', '--quiet', 'python', '-c', 'import json; from webhooks.main import create_app; print(json.dumps(create_app().openapi()))'],
  // Pin the settings that change the routes, so a local backend/.env can't change the output.
  { cwd: backendDir, encoding: 'utf8', env: { ...process.env, MOCK_RECEIVER_ENABLED: 'true' } }
)

const header = '// Generated by `pnpm gen:api` from the backend OpenAPI schema. Do not edit.\n\n'
const generated = header + astToString(await openapiTS(JSON.parse(schema)))

if (check) {
  const current = await readFile(outFile, 'utf8').catch(() => '')
  if (current !== generated) {
    console.error('app/api/schema.d.ts is stale: the backend API changed. Run `pnpm gen:api`.')
    process.exit(1)
  }
  console.log('app/api/schema.d.ts is up to date.')
} else {
  await writeFile(outFile, generated)
  console.log('Wrote app/api/schema.d.ts')
}
